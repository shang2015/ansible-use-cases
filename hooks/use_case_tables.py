"""MkDocs hook: render the "Collections & key content" section of every use case.

Use case pages declare what delivers them in front matter:

    collections: [network.backup, ansible.netcommon]
    key_content: [network.backup.backup, ansible.netcommon.cli_backup]
    examples:
      - title: Network backup demo
        url: https://github.com/...

The hook looks every reference up in data/content.json (generated by
scripts/extract_content.py) and appends a table with the content type, the
author's own description, and links. Unknown references are reported, and fail
the build under `mkdocs build --strict`.
"""
from __future__ import annotations

import json
import logging
from pathlib import Path

import yaml

log = logging.getLogger("mkdocs.hooks.use_case_tables")
ROOT = Path(__file__).resolve().parent.parent
_INDEX: dict | None = None


def _load():
    global _INDEX
    if _INDEX is not None:
        return _INDEX
    cols = {c["fqcn"]: c for c in yaml.safe_load((ROOT / "data" / "collections.yml").read_text())}
    content = {}
    p = ROOT / "data" / "content.json"
    if p.exists():
        for col in json.loads(p.read_text()):
            for item in col["items"]:
                content.setdefault(item["fqcn"], item)
    _INDEX = {"collections": cols, "content": content}
    return _INDEX


def _badge(kind: str) -> str:
    kind = (kind or "").lower()
    if "validated" in kind:
        return '<span class="uc-badge uc-validated">Validated</span>'
    if "certified" in kind:
        return '<span class="uc-badge uc-certified">Certified</span>'
    return f'<span class="uc-badge">{kind or "n/a"}</span>'


def _col_link(fqcn: str, depth: int) -> str:
    return f"[`{fqcn}`]({'../' * depth}collections/{fqcn}.md)"


def _use_case_list(page, files) -> str:
    """Bullet list of the use case pages that sit in the same folder as an index page."""
    folder = page.file.src_uri.rsplit("/", 1)[0] + "/"
    rows = []
    for f in files.documentation_pages():
        uri = f.src_uri
        if not uri.startswith(folder) or uri == page.file.src_uri or "/" in uri[len(folder):]:
            continue
        if uri.rsplit("/", 1)[-1].startswith("_"):
            continue
        text = Path(f.abs_src_path).read_text()
        fm = {}
        if text.startswith("---"):
            try:
                fm = yaml.safe_load(text.split("---", 2)[1]) or {}
            except Exception:
                fm = {}
        title = fm.get("title") or uri.rsplit("/", 1)[-1][:-3]
        summary = fm.get("summary", "")
        rows.append((fm.get("order", 999), title, uri[len(folder):], summary))
    if not rows:
        return "_Use cases for this domain are being written. Contributions welcome._"
    out = ["| Use case | Summary |", "|---|---|"]
    for _, title, rel, summary in sorted(rows):
        out.append(f"| [{title}]({rel}) | {str(summary).replace('|', '/')} |")
    return "\n".join(out)


def on_page_markdown(markdown: str, page, config, files):
    if "<!-- use-case-list -->" in markdown:
        markdown = markdown.replace("<!-- use-case-list -->", _use_case_list(page, files))
    meta = page.meta or {}
    cols = meta.get("collections") or []
    keys = meta.get("key_content") or []
    examples = meta.get("examples") or []
    if not (cols or keys or examples):
        return markdown
    idx = _load()
    depth = page.file.src_uri.count("/")
    out = ["", "## Collections & key content", ""]
    if cols:
        out += ["| Collection | Support | Provider | What it covers |", "|---|---|---|---|"]
        for fqcn in cols:
            c = idx["collections"].get(fqcn)
            if not c:
                log.warning("%s: unknown collection '%s'", page.file.src_uri, fqcn)
                out.append(f"| `{fqcn}` | – | – | – |")
                continue
            desc = (c.get("description") or "").replace("|", "\\|")
            out.append(f"| {_col_link(fqcn, depth)} | {_badge(c.get('content_type'))} | {c.get('provider') or ''} | {desc} |")
        out.append("")
    if keys:
        out += ["| Module / role / plugin | Type | What it does |", "|---|---|---|"]
        for ref in keys:
            item = idx["content"].get(ref)
            if not item:
                log.warning("%s: unknown content reference '%s'", page.file.src_uri, ref)
                out.append(f"| `{ref}` | – | – |")
                continue
            col = ref.rsplit(".", 1)[0] if item["type"] != "playbook" else ".".join(ref.split(".")[:2])
            col = ".".join(ref.split(".")[:2])
            anchor = item["name"].replace(".", "").replace("_", "-").lower()
            link = f"[`{ref}`]({'../' * depth}collections/{col}.md#{anchor})"
            desc = (item.get("short_description") or "").replace("|", "\\|")
            out.append(f"| {link} | {item['type'].replace('_', ' ')} | {desc} |")
        out.append("")
    if examples:
        out += ["### Example repositories and demos", ""]
        for ex in examples:
            note = f" — {ex['note']}" if ex.get("note") else ""
            out.append(f"- [{ex['title']}]({ex['url']}){note}")
        out.append("")
    return markdown.rstrip() + "\n" + "\n".join(out)
