"""MkDocs hook: render every use case in the format of the original
"Ansible Automation - Use Cases" document, one table per use case:

    Description | Collection | Key content | Notes

Use case pages keep the prose in two sections and declare what delivers them
in front matter:

    collections: [network.backup, ansible.netcommon]
    key_content: [network.backup.backup, ansible.netcommon.cli_backup]
    examples:                       # optional, listed under Notes
      - title: Network backup demo
        url: https://github.com/...

    ## Description
    ...
    ## Notes
    ...

The hook looks every reference up in data/content.json (generated by
scripts/extract_content.py). On a domain index page, `<!-- use-case-list -->`
is replaced with the tables of every use case in that folder. Unknown
references and broken links are logged as warnings, which fail
`mkdocs build --strict`.
"""
from __future__ import annotations

import html
import json
import logging
import posixpath
import re
from pathlib import Path

import markdown as md_lib
import yaml
from mkdocs.utils import get_relative_url

log = logging.getLogger("mkdocs.hooks.use_case_tables")
ROOT = Path(__file__).resolve().parent.parent
_INDEX: dict | None = None
_MD = md_lib.Markdown(extensions=["tables", "attr_list"])
MARKER = "<!-- use-case-list -->"


def _load():
    global _INDEX
    if _INDEX is not None:
        return _INDEX
    cols = {c["fqcn"]: c for c in yaml.safe_load((ROOT / "data" / "collections.yml").read_text())}
    content = {}
    p = ROOT / "data" / "content.json"
    if p.exists():
        for col in json.loads(p.read_text()):
            for item in col["items"]:
                content.setdefault(item["fqcn"], item)
    _INDEX = {"collections": cols, "content": content}
    return _INDEX


def _support(kind: str) -> tuple[str, str]:
    kind = (kind or "").lower()
    if "validated" in kind:
        return "Validated", "uc-validated"
    if "certified" in kind:
        return "Certified", "uc-certified"
    return (kind or "n/a"), ""


def stamp(c: dict) -> str:
    """Version and last-updated date of a collection, from the Ecosystem Catalog."""
    bits = []
    if c.get("latest_version"):
        bits.append(f"v{c['latest_version']}")
    if c.get("last_updated"):
        bits.append(f"updated {c['last_updated']}")
    return f' <span class="uc-stamp">{" · ".join(bits)}</span>' if bits else ""


def split_front_matter(text: str) -> tuple[dict, str]:
    if not text.startswith("---"):
        return {}, text
    _, raw, body = text.split("---", 2)
    try:
        return yaml.safe_load(raw) or {}, body
    except Exception:  # noqa: BLE001
        return {}, body


def sections(body: str) -> dict[str, str]:
    parts = re.split(r"^## (.+)$", body, flags=re.M)
    return {parts[i].strip(): parts[i + 1].strip() for i in range(1, len(parts) - 1, 2)}


def _md(text: str, src_uri: str, page, files) -> str:
    """Markdown -> HTML, with links to other .md files rewritten to page URLs."""
    _MD.reset()
    out = _MD.convert(text or "")

    def fix(m):
        href = m.group(1)
        if re.match(r"^[a-z]+:|^#|^/", href) or ".md" not in href:
            return m.group(0)
        path, _, frag = href.partition("#")
        target = posixpath.normpath(posixpath.join(posixpath.dirname(src_uri), path))
        f = files.get_file_from_path(target)
        if f is None:
            log.warning("%s: link to '%s' does not resolve", src_uri, href)
            return m.group(0)
        url = get_relative_url(f.url, page.url)
        return f'href="{url}{"#" + frag if frag else ""}"'

    return re.sub(r'href="([^"]+)"', fix, out)


def use_case_table(fm: dict, body: str, src_uri: str, page, files) -> str:
    idx = _load()
    depth = page.file.src_uri.count("/")
    prefix = "../" * depth
    s = sections(body)

    col_items = []
    for fqcn in fm.get("collections") or []:
        c = idx["collections"].get(fqcn)
        if not c:
            log.warning("%s: unknown collection '%s'", src_uri, fqcn)
            col_items.append(f"<li><code>{html.escape(fqcn)}</code></li>")
            continue
        label, cls = _support(c.get("content_type"))
        url = get_relative_url(files.get_file_from_path(f"collections/{fqcn}.md").url, page.url) \
            if files.get_file_from_path(f"collections/{fqcn}.md") else f"{prefix}collections/{fqcn}/"
        col_items.append(f'<li><a href="{url}"><code>{html.escape(fqcn)}</code></a> '
                         f'<span class="uc-badge {cls}">{label}</span> {html.escape(c.get("provider") or "")}{stamp(c)}</li>')

    key_items = []
    for ref in fm.get("key_content") or []:
        item = idx["content"].get(ref)
        if not item:
            log.warning("%s: unknown content reference '%s'", src_uri, ref)
            key_items.append(f"<li><code>{html.escape(ref)}</code></li>")
            continue
        col = ".".join(ref.split(".")[:2])
        f = files.get_file_from_path(f"collections/{col}.md")
        base = get_relative_url(f.url, page.url) if f else f"{prefix}collections/{col}/"
        a = item["name"].replace(".", "").replace("_", "-").lower()
        kind = item["type"].replace("_", " ")
        key_items.append(f'<li><a href="{base}#{a}"><code>{html.escape(ref)}</code></a> '
                         f'<span class="uc-kind">{kind}</span> {html.escape(item.get("short_description") or "")}</li>')

    notes = _md(s.get("Notes", ""), src_uri, page, files)
    examples = fm.get("examples") or []
    if examples:
        notes += "<p><strong>Examples:</strong></p><ul>" + "".join(
            f'<li><a href="{html.escape(ex["url"])}">{html.escape(ex["title"])}</a>'
            f'{" — " + html.escape(ex["note"]) if ex.get("note") else ""}</li>' for ex in examples) + "</ul>"

    rows = [
        ("Description", _md(s.get("Description", ""), src_uri, page, files)),
        ("Collection", f"<ul>{''.join(col_items)}</ul>" if col_items else ""),
        ("Key content", f"<ul>{''.join(key_items)}</ul>" if key_items else ""),
        ("Notes", notes),
    ]
    return ('<table class="uc-table"><tbody>'
            + "".join(f"<tr><th>{k}</th><td>{v}</td></tr>" for k, v in rows if v)
            + "</tbody></table>")


def _use_case_list(page, files) -> str:
    """Every use case in the same folder as an index page, each as its table."""
    folder = page.file.src_uri.rsplit("/", 1)[0] + "/"
    rows = []
    for f in files.documentation_pages():
        uri = f.src_uri
        if not uri.startswith(folder) or uri == page.file.src_uri or "/" in uri[len(folder):]:
            continue
        if uri.rsplit("/", 1)[-1].startswith("_"):
            continue
        fm, body = split_front_matter(Path(f.abs_src_path).read_text())
        title = fm.get("title") or uri.rsplit("/", 1)[-1][:-3]
        rows.append((fm.get("order", 999), title, uri, fm, body, f))
    if not rows:
        return "_Use cases for this domain are being written. Contributions welcome._"
    out = []
    for _, title, uri, fm, body, f in sorted(rows, key=lambda r: (r[0], r[1])):
        link = get_relative_url(f.url, page.url)
        out += [f"### Use Case: {title}", "",
                f'<p class="uc-open"><a href="{link}">Open this use case</a></p>',
                use_case_table(fm, body, uri, page, files), ""]
    return "\n".join(out)


def on_page_markdown(markdown: str, page, config, files):
    if MARKER in markdown:
        return markdown.replace(MARKER, _use_case_list(page, files))
    meta = page.meta or {}
    if not page.file.src_uri.startswith("use-cases/") or not (meta.get("collections") or meta.get("key_content")):
        return markdown
    head, sep, _ = markdown.partition("\n## ")
    table = use_case_table(meta, markdown, page.file.src_uri, page, files)
    return head.rstrip() + "\n\n" + table + "\n"
